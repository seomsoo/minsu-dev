/** 내려다보는 각도. 단면 원이 납작한 타원으로 보인다 */
const TILT = (32 * Math.PI) / 180;
const COS = Math.cos(TILT);
const SIN = Math.sin(TILT);
/** 도면 크기: 폰 전체 높이 = 100 */
const H = 100;

function radiusAt(t: number) {
  const i = Math.min(
    PROFILE.length - 1,
    Math.max(0, Math.round(t * (PROFILE.length - 1))),
  );
  return PROFILE[i][1] * H;
}

const cy = (t: number) => -t * H * COS;
const fmt = (n: number) => n.toFixed(2);

/** 높이 t의 단면 타원에서 앞쪽 반(아래 호) 또는 뒤쪽 반(위 호) */
function arc(
  t: number,
  half: 'front' | 'back',
  from: 'left' | 'right' = 'left',
) {
  const r = radiusAt(t);
  const y = cy(t);
  const ry = r * SIN;
  const [x0, x1] = from === 'left' ? [-r, r] : [r, -r];
  // 왼→오 기준: 앞쪽(아래) 호는 sweep 0, 뒤쪽(위) 호는 sweep 1
  const sweep = (half === 'front') === (from === 'left') ? 0 : 1;
  return {
    start: [x0, y],
    d: `A ${fmt(r)} ${fmt(ry)} 0 0 ${sweep} ${fmt(x1)} ${fmt(y)}`,
  };
}

function edge(t0: number, t1: number, side: -1 | 1) {
  const pts: string[] = [];
  const n = Math.max(2, Math.round((t1 - t0) * 120));
  for (let i = 0; i <= n; i++) {
    const t = t0 + ((t1 - t0) * i) / n;
    pts.push(`${fmt(side * radiusAt(t))} ${fmt(cy(t))}`);
  }
  return pts;
}

export type Part = {
  /** 채움(뒤를 가리는 면): 옆선 + 위 타원 뒤쪽 호 + 아래 타원 앞쪽 호로 닫은 모양 */
  fill: string;
  /** 선: 옆선, 위 타원 전체, 아래 테 앞쪽 호, 결 무늬 */
  lines: string[];
  /** 벌어질 때 움직이는 거리. 양수는 위로, 음수는 아래로 (가운데를 기준으로 위아래로 벌어진다) */
  lift: number;
  /** 아래·위 경계의 반지름과 높이 (안내선용) */
  bottom: { r: number; y: number };
  top: { r: number; y: number };
};

function part(
  t0: number,
  t1: number,
  lift: number,
  rings: number[] = [],
  cap = true,
  /** 머리처럼 위를 구의 반지름으로 둥글게 닫는다 */
  dome?: number,
): Part {
  const left = edge(t0, t1, -1);
  const right = edge(t0, t1, 1).reverse();
  const bottomFront = arc(t0, 'front', 'right');
  // 위쪽 마감: 윗면 타원의 뒤쪽 호, 또는 머리라면 구의 둥근 윤곽
  const over = dome
    ? `A ${fmt(dome)} ${fmt(dome)} 0 0 1 ${fmt(radiusAt(t1))} ${fmt(cy(t1))}`
    : arc(t1, 'back', 'left').d;
  const fill = `M ${left.join(' L ')} ${over} L ${right.join(' L ')} ${bottomFront.d} Z`;
  const lines = [
    dome
      ? `M ${left.join(' L ')} ${over} L ${right.join(' L ')}`
      : `M ${left.join(' L ')}`,
    ...(dome ? [] : [`M ${edge(t0, t1, 1).join(' L ')}`]),
    (() => {
      const a = arc(t0, 'front');
      return `M ${fmt(a.start[0])} ${fmt(a.start[1])} ${a.d}`;
    })(),
  ];
  if (cap) {
    // 위에서 내려다보므로 윗면 타원은 통째로 보인다
    const r = radiusAt(t1);
    const ry = r * SIN;
    const y = cy(t1);
    lines.push(
      `M ${fmt(-r)} ${fmt(y)} A ${fmt(r)} ${fmt(ry)} 0 0 1 ${fmt(r)} ${fmt(y)} A ${fmt(r)} ${fmt(ry)} 0 0 1 ${fmt(-r)} ${fmt(y)}`,
    );
  }
  for (const t of rings) {
    const a = arc(t, 'front');
    lines.push(`M ${fmt(a.start[0])} ${fmt(a.start[1])} ${a.d}`);
  }
  return {
    fill,
    lines,
    lift,
    bottom: { r: radiusAt(t0), y: cy(t0) },
    top: { r: radiusAt(t1), y: cy(t1) },
  };
}

